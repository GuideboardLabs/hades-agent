//! The systemd units, rendered by the binary that runs under them.
//!
//! A unit file names an absolute path that only the installer knows, so it cannot be a static file in a
//! tarball: `hades service install` renders it from the prefix and the home it was told. That also makes the
//! file a generated artifact, and generated artifacts need an ownership rule rather than a hope. The first
//! line is the marker. A file that starts with it is ours and is rewritten on every install, including when
//! the template changed in a new build; a file that does not is somebody else's unit and is refused by name
//! unless `--force` says otherwise.
//!
//! The daemon unit stops through `hades shutdown` rather than SIGTERM alone, because the daemon's own
//! contract is that a stop is a request honored at the next boundary. The `-` prefix keeps a shutdown that
//! finds nothing alive from leaving a failed unit behind. `TimeoutStopSec` is the limit on that grace: a model
//! call still in flight is cut after it.

use std::path::{Path, PathBuf};

/// The two unit files, named so a test and a person use the same strings.
pub const DAEMON: &str = "hades-daemon.service";
pub const GATEWAY: &str = "hades-gateway.service";

/// The first line of a file this binary owns. The version follows so a person can tell two generations
/// apart without opening the service body.
pub const MARKER: &str = "# Generated by hades";

/// Both units, rendered together: the gateway's `Requires=` must name the daemon, and one function that
/// writes both cannot drift from that.
pub struct Units {
    pub daemon: String,
    pub gateway: String,
}

/// The version this build stamps into the marker.
fn version() -> &'static str {
    env!("CARGO_PKG_VERSION")
}

/// Render both units for an installed prefix and a home.
pub fn render(prefix: &Path, home: &Path) -> Result<Units, String> {
    let binary = prefix.join("bin").join("hades");
    let binary = systemd_arg(&binary.to_string_lossy())?;
    let state = systemd_arg(&home.to_string_lossy())?;
    let mut environment = vec![format!(
        "Environment={}",
        systemd_environment("HADES_HOME", &home.to_string_lossy())?
    )];
    // A unit starts with systemd's minimal PATH, which may not contain the toolchain that ran the
    // installer. The profile's check is `cargo test`, so the
    // installer's PATH and toolchain homes are recorded here: a service that cannot see the toolchain its
    // own profiles name is broken, and the failure would look like the model's.
    for (key, value) in [
        ("PATH", std::env::var("PATH").unwrap_or_default()),
        (
            "CARGO_HOME",
            std::env::var("CARGO_HOME").unwrap_or_default(),
        ),
        (
            "RUSTUP_HOME",
            std::env::var("RUSTUP_HOME").unwrap_or_default(),
        ),
        (
            "CARGO_TARGET_DIR",
            std::env::var("CARGO_TARGET_DIR").unwrap_or_default(),
        ),
    ] {
        if !value.is_empty() {
            environment.push(format!("Environment={}", systemd_environment(key, &value)?));
        }
    }
    let environment = environment.join("\n         ");
    let marker = format!(
        "{MARKER} {}. Edits are overwritten by `hades service install`.",
        version()
    );

    let daemon = format!(
        "{marker}\n\
         [Unit]\n\
         Description=Hades daemon (sessions, jobs, approvals)\n\
         StartLimitIntervalSec=60\n\
         StartLimitBurst=5\n\
         \n\
         [Service]\n\
         Type=simple\n\
         WorkingDirectory=%h\n\
         {environment}\n\
         ExecStart={binary} daemon --state {state}\n\
         ExecStop=-{binary} shutdown --state {state}\n\
         Restart=on-failure\n\
         RestartSec=2\n\
         TimeoutStopSec=15\n\
         NoNewPrivileges=yes\n\
         PrivateTmp=yes\n\
         \n\
         [Install]\n\
         WantedBy=default.target\n"
    );

    let gateway = format!(
        "{marker}\n\
         [Unit]\n\
         Description=Hades Telegram gateway\n\
         After=hades-daemon.service\n\
         Requires=hades-daemon.service\n\
         StartLimitIntervalSec=60\n\
         StartLimitBurst=5\n\
         \n\
         [Service]\n\
         Type=simple\n\
         WorkingDirectory=%h\n\
         {environment}\n\
         ExecStart={binary} gateway --state {state}\n\
         Restart=on-failure\n\
         RestartSec=10\n\
         NoNewPrivileges=yes\n\
         PrivateTmp=yes\n\
         \n\
         [Install]\n\
         WantedBy=default.target\n"
    );

    Ok(Units { daemon, gateway })
}

/// Write both units into `out`, in daemon-then-gateway order.
///
/// An existing file is rewritten when it carries the marker, and refused when it does not. The refusal
/// names the path and the way through, because a person who hand-wrote a unit needs to know which file was
/// not touched rather than discovering it later.
pub fn write(prefix: &Path, home: &Path, out: &Path, force: bool) -> Result<Vec<PathBuf>, String> {
    let units = render(prefix, home)?;
    std::fs::create_dir_all(out)
        .map_err(|error| format!("could not make {}: {error}", out.display()))?;

    let mut written = Vec::new();
    for (name, text) in [(DAEMON, &units.daemon), (GATEWAY, &units.gateway)] {
        let path = out.join(name);
        if let Ok(existing) = std::fs::read_to_string(&path)
            && !force
            && !existing.starts_with(MARKER)
        {
            return Err(format!(
                "refusing to overwrite {}: it was not written by `hades service install`. Move it \
                 aside, or pass `--force` to replace it",
                path.display()
            ));
        }
        std::fs::write(&path, text)
            .map_err(|error| format!("could not write {}: {error}", path.display()))?;
        written.push(path);
    }
    Ok(written)
}

/// One argument in a unit's command line.
///
/// systemd reads double quotes and backslash escapes, and an unquoted path splits on whitespace. A newline
/// cannot be represented at all, so it is refused rather than silently truncated. A percent sign is a
/// specifier (`%h`, `%t`) wherever systemd expands one, and quoting does not turn that off: a literal
/// percent has to be doubled. Environment= is not expanded, so it does not go through here.
fn systemd_arg(text: &str) -> Result<String, String> {
    if text.contains('\n') || text.contains('\r') {
        return Err("a unit cannot carry a path with a newline in it".to_string());
    }
    Ok(quote(&text.replace('%', "%%")))
}

/// `Environment=NAME=value`, quoted as one assignment when the value needs it.
///
/// `Environment=` performs specifier expansion too (systemd.exec: "Specifier expansion is performed"), and
/// quoting does not turn it off, so a literal percent is doubled here as well.
fn systemd_environment(name: &str, value: &str) -> Result<String, String> {
    if value.contains('\n') || value.contains('\r') {
        return Err("a unit cannot carry a path with a newline in it".to_string());
    }
    let assignment = format!("{name}={}", value.replace('%', "%%"));
    if needs_quotes(value) {
        Ok(format!("\"{}\"", escape(&assignment)))
    } else {
        Ok(assignment)
    }
}

fn quote(text: &str) -> String {
    if needs_quotes(text) {
        format!("\"{}\"", escape(text))
    } else {
        text.to_string()
    }
}

fn needs_quotes(text: &str) -> bool {
    text.is_empty()
        || text.chars().any(|character| {
            character.is_whitespace() || matches!(character, '"' | '\'' | '\\' | ';')
        })
}

fn escape(text: &str) -> String {
    text.replace('\\', "\\\\").replace('"', "\\\"")
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn a_plain_path_is_left_alone() {
        assert_eq!(
            systemd_arg("/home/a/.local/bin/hades").unwrap(),
            "/home/a/.local/bin/hades"
        );
    }

    #[test]
    fn a_path_with_a_space_is_one_argument() {
        assert_eq!(
            systemd_arg("/home/a b/bin/hades").unwrap(),
            "\"/home/a b/bin/hades\""
        );
    }

    #[test]
    fn an_environment_assignment_quotes_name_and_value_together() {
        assert_eq!(
            systemd_environment("HADES_HOME", "/home/a b/.hades").unwrap(),
            "\"HADES_HOME=/home/a b/.hades\""
        );
    }

    #[test]
    fn an_environment_value_doubles_a_percent_too() {
        assert_eq!(
            systemd_environment("HADES_HOME", "/home/a%h b/.hades").unwrap(),
            "\"HADES_HOME=/home/a%%h b/.hades\""
        );
    }

    #[test]
    fn a_newline_is_refused_rather_than_truncated() {
        assert!(systemd_arg("/home/a\nb").is_err());
    }

    /// A unit started from systemd must inherit the target directory the installer used, or a build
    /// the agent starts from inside the service lands on the small root filesystem.
    #[test]
    fn the_units_carry_the_target_directory_when_one_is_set() {
        // SAFETY: this test sets the variable only to read it back through `render`; no other test
        // reads or writes `CARGO_TARGET_DIR`.
        unsafe {
            std::env::set_var("CARGO_TARGET_DIR", "/var/tmp/hades-target");
        }
        let units = render(Path::new("/opt/hades"), Path::new("/home/a/.hades")).unwrap();
        assert!(
            units
                .daemon
                .contains("Environment=CARGO_TARGET_DIR=/var/tmp/hades-target"),
            "the daemon unit must carry the build directory:\n{}",
            units.daemon
        );
        assert!(
            units
                .gateway
                .contains("Environment=CARGO_TARGET_DIR=/var/tmp/hades-target"),
            "the gateway unit must carry the build directory:\n{}",
            units.gateway
        );
    }

    /// `%h` in a path is the user's home to systemd, not a directory named `%h`. A literal percent is `%%`.
    #[test]
    fn a_percent_is_doubled_so_systemd_does_not_expand_it() {
        assert_eq!(systemd_arg("/home/a%h/b").unwrap(), "/home/a%%h/b");
        assert_eq!(
            systemd_arg("/home/a b%t/bin/hades").unwrap(),
            "\"/home/a b%%t/bin/hades\""
        );
    }
}
