//! The oracle for `hades service install`: two files a supervisor can read, and an ownership rule that
//! keeps a hand-written unit from being clobbered.
//!
//! Every path is a flag, so nothing here writes the systemd directory or the Hades home of the machine the
//! tests run on.

use std::path::{Path, PathBuf};

use harness::cli;

fn scratch(name: &str) -> PathBuf {
    let dir = scratch_base().join(format!("hades-service-{name}-{}", std::process::id()));
    let _ = std::fs::remove_dir_all(&dir);
    std::fs::create_dir_all(&dir).expect("a scratch directory");
    dir
}

fn hades(args: &[&str]) -> (i32, String) {
    isolated_home();
    let owned: Vec<String> = args.iter().map(|arg| arg.to_string()).collect();
    let mut out: Vec<u8> = Vec::new();
    let code = cli::run(&owned, &mut out);
    (code, String::from_utf8_lossy(&out).into_owned())
}

fn install(dir: &Path) -> (i32, String) {
    let prefix = dir.join("prefix");
    let home = dir.join("home");
    let out = dir.join("units");
    hades(&[
        "service",
        "install",
        "--prefix",
        &prefix.display().to_string(),
        "--home",
        &home.display().to_string(),
        "--out",
        &out.display().to_string(),
    ])
}

#[test]
fn both_units_name_the_install_and_the_daemon_first() {
    let dir = scratch("both");
    let (code, text) = install(&dir);
    assert_eq!(code, 0, "{text}");

    let units = dir.join("units");
    assert!(
        text.contains(&units.join("hades-daemon.service").display().to_string()),
        "{text}"
    );
    assert!(
        text.contains(&units.join("hades-gateway.service").display().to_string()),
        "{text}"
    );

    let daemon =
        std::fs::read_to_string(units.join("hades-daemon.service")).expect("a daemon unit");
    assert!(
        daemon.starts_with("# Generated by hades"),
        "the marker is the ownership rule: {daemon}"
    );
    for line in [
        "Description=Hades daemon",
        "Type=simple",
        "WorkingDirectory=%h",
        "Restart=on-failure",
        "RestartSec=2",
        "TimeoutStopSec=15",
        "NoNewPrivileges=yes",
        "PrivateTmp=yes",
        "WantedBy=default.target",
    ] {
        assert!(daemon.contains(line), "{line} is missing from:\n{daemon}");
    }

    let prefix = dir.join("prefix");
    let home = dir.join("home");
    assert!(
        daemon.contains(&format!(
            "ExecStart={}/bin/hades daemon --state {}",
            prefix.display(),
            home.display()
        )),
        "{daemon}"
    );
    assert!(
        daemon.contains(&format!(
            "ExecStop=-{}/bin/hades shutdown --state {}",
            prefix.display(),
            home.display()
        )),
        "a stop is a request, and a failed stop is not a failed unit:\n{daemon}"
    );
    assert!(
        daemon.contains(&format!("Environment=HADES_HOME={}", home.display())),
        "the daemon has no --config flag, so the home travels in the environment:\n{daemon}"
    );

    let gateway =
        std::fs::read_to_string(units.join("hades-gateway.service")).expect("a gateway unit");
    assert!(gateway.contains("After=hades-daemon.service"), "{gateway}");
    assert!(
        gateway.contains("Requires=hades-daemon.service"),
        "{gateway}"
    );
    assert!(gateway.contains("RestartSec=10"), "{gateway}");
}

#[test]
fn a_second_install_writes_the_same_bytes() {
    let dir = scratch("twice");
    let (code, text) = install(&dir);
    assert_eq!(code, 0, "{text}");
    let units = dir.join("units");
    let before: Vec<Vec<u8>> = ["hades-daemon.service", "hades-gateway.service"]
        .iter()
        .map(|name| std::fs::read(units.join(name)).expect("a unit"))
        .collect();

    let (code, text) = install(&dir);
    assert_eq!(code, 0, "a re-install is not an error: {text}");
    let after: Vec<Vec<u8>> = ["hades-daemon.service", "hades-gateway.service"]
        .iter()
        .map(|name| std::fs::read(units.join(name)).expect("a unit"))
        .collect();
    assert_eq!(before, after);
}

#[test]
fn a_hand_written_unit_is_refused_until_force() {
    let dir = scratch("foreign");
    let units = dir.join("units");
    std::fs::create_dir_all(&units).expect("the units directory");
    let path = units.join("hades-daemon.service");
    let hand = "[Unit]\nDescription=mine\n";
    std::fs::write(&path, hand).expect("a hand-written unit");

    let (code, text) = install(&dir);
    assert_eq!(code, 2, "{text}");
    assert!(text.contains("refusing to overwrite"), "{text}");
    assert!(text.contains(&path.display().to_string()), "{text}");
    assert_eq!(
        std::fs::read_to_string(&path).expect("the unit"),
        hand,
        "a refused install touches nothing"
    );

    let prefix = dir.join("prefix");
    let home = dir.join("home");
    let out = dir.join("units");
    let (code, text) = hades(&[
        "service",
        "install",
        "--prefix",
        &prefix.display().to_string(),
        "--home",
        &home.display().to_string(),
        "--out",
        &out.display().to_string(),
        "--force",
    ]);
    assert_eq!(code, 0, "{text}");
    assert!(
        std::fs::read_to_string(&path)
            .expect("the unit")
            .starts_with("# Generated by hades"),
        "force replaces the foreign file"
    );
}

#[test]
fn a_missing_out_directory_is_created() {
    let dir = scratch("nested");
    let prefix = dir.join("prefix");
    let home = dir.join("home");
    let out = dir.join("a").join("b").join("c");
    let (code, text) = hades(&[
        "service",
        "install",
        "--prefix",
        &prefix.display().to_string(),
        "--home",
        &home.display().to_string(),
        "--out",
        &out.display().to_string(),
    ]);
    assert_eq!(code, 0, "{text}");
    assert!(out.join("hades-daemon.service").is_file());
    assert!(out.join("hades-gateway.service").is_file());
}

#[test]
fn a_path_with_a_space_is_quoted_as_one_argument() {
    let dir = scratch("spaces");
    let prefix = dir.join("a b");
    let home = dir.join("x y");
    let out = dir.join("units");
    let (code, text) = hades(&[
        "service",
        "install",
        "--prefix",
        &prefix.display().to_string(),
        "--home",
        &home.display().to_string(),
        "--out",
        &out.display().to_string(),
    ]);
    assert_eq!(code, 0, "{text}");
    let daemon = std::fs::read_to_string(out.join("hades-daemon.service")).expect("a unit");
    assert!(
        daemon.contains(&format!(
            "ExecStart=\"{}/bin/hades\" daemon --state \"{}\"",
            prefix.display(),
            home.display()
        )),
        "{daemon}"
    );
    assert!(
        daemon.contains(&format!("Environment=\"HADES_HOME={}\"", home.display())),
        "{daemon}"
    );
}

#[test]
fn an_unknown_service_verb_says_what_exists() {
    let (code, text) = hades(&["service", "remove"]);
    assert_eq!(code, 2, "{text}");
    assert!(text.contains("hades service install"), "{text}");
}

fn scratch_base() -> PathBuf {
    let base = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../target/scratch");
    std::fs::create_dir_all(&base).expect("the scratch base");
    base.canonicalize().unwrap_or(base)
}

fn isolated_home() {
    use std::sync::OnceLock;
    static ONCE: OnceLock<()> = OnceLock::new();
    ONCE.get_or_init(|| {
        let home = scratch_base().join(format!("hades-service-home-{}", std::process::id()));
        std::fs::create_dir_all(&home).expect("an isolated home");
        // SAFETY: set once before any CLI call, and no other thread in this binary reads it first.
        unsafe { std::env::set_var("HADES_HOME", &home) };
    });
}
